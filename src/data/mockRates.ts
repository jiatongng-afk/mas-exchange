// Generates 30 business days of consistent historical points ending at target date
function generateHistory(baseRate: number, volatility: number, trend: number[]): { date: string; rate: number; high: number; low: number }[] {
  const points: { date: string; rate: number; high: number; low: number }[] = [];
  const baseDate = new Date('2026-10-15T17:00:00+08:00');
  
  // Create 30 historical trading day dates (excluding weekends)
  const tradingDays: string[] = [];
  const curr = new Date(baseDate);
  while (tradingDays.length < 30) {
    const day = curr.getDay();
    if (day !== 0 && day !== 6) { // Skip Sunday (0) and Saturday (6)
      const iso = curr.toISOString().split('T')[0];
      tradingDays.unshift(iso);
    }
    curr.setDate(curr.getDate() - 1);
  }

  // Build series using predefined smooth curve
  for (let i = 0; i < 30; i++) {
    const factor = trend[i % trend.length];
    const val = baseRate * (1 + factor * volatility);
    const daySpread = val * 0.0035;
    points.push({
      date: tradingDays[i],
      rate: Number(val.toFixed(4)),
      high: Number((val + daySpread).toFixed(4)),
      low: Number((val - daySpread).toFixed(4)),
    });
  }

  // Ensure last point is exactly baseRate
  if (points.length > 0) {
    points[points.length - 1].rate = baseRate;
  }
  return points;
}

